// Prepares the web directory of an app for the browser cache of
// cloud_firestore_dart_sqlite:
//
//     dart run cloud_firestore_dart_sqlite:setup_web [web directory]
//
// Run it from the app's package directory (the one with its pubspec.yaml)
// after `dart pub get` or `flutter pub get`, and again whenever the resolved
// version of this package or of `sqlite3` changes. The web directory defaults
// to `web`, which `flutter build web` and the usual Dart web setups copy next
// to the page.
//
// It compiles the OPFS worker to `<web directory>/sqlite_opfs_worker.js` with
// `dart compile js -O2`, and prints where to download the `sqlite3.wasm` that
// goes with the resolved `sqlite3` version (it does not download anything).
//
// Options:
//   --no-worker   skip the worker (an app that only uses IndexedDB)

import 'dart:convert';
import 'dart:io';

Future<void> main(List<String> arguments) async {
  bool worker = true;
  final List<String> rest = <String>[];
  for (final String argument in arguments) {
    if (argument == '--no-worker') {
      worker = false;
    } else if (argument == '-h' || argument == '--help') {
      stdout.writeln(
        'Usage: dart run cloud_firestore_dart_sqlite:setup_web '
        '[--no-worker] [web directory]\n\n'
        'Compiles the OPFS worker to <web directory>/sqlite_opfs_worker.js '
        'and prints which sqlite3.wasm to put next to it. The web directory '
        'defaults to "web". Run it from the directory of your pubspec.yaml.',
      );
      return;
    } else if (argument.startsWith('-')) {
      stderr.writeln('Unknown option $argument (see --help).');
      exitCode = 64;
      return;
    } else {
      rest.add(argument);
    }
  }
  if (rest.length > 1) {
    stderr.writeln('Give at most one web directory (see --help).');
    exitCode = 64;
    return;
  }
  final Directory webDir = Directory(rest.isEmpty ? 'web' : rest.single);

  final File? packageConfig = _findUp('.dart_tool/package_config.json');
  if (packageConfig == null) {
    stderr.writeln(
      'No .dart_tool/package_config.json here or above: run `dart pub get` '
      '(or `flutter pub get`) in your app first.',
    );
    exitCode = 1;
    return;
  }
  final String? sqlite3Version = _sqlite3Version(packageConfig);

  if (!webDir.existsSync()) {
    webDir.createSync(recursive: true);
  }

  if (worker) {
    // An entry point next to the package config, so that the compiler
    // resolves `package:` imports with the app's own dependencies.
    final Directory entryDir = Directory(
      '${packageConfig.parent.path}/cloud_firestore_dart_sqlite',
    )..createSync(recursive: true);
    final File entry = File('${entryDir.path}/sqlite_opfs_worker.dart')
      ..writeAsStringSync(
        '// Generated by `dart run cloud_firestore_dart_sqlite:setup_web`.\n'
        "import 'package:cloud_firestore_dart_sqlite/opfs_worker.dart';\n\n"
        'void main() => runOpfsWorker();\n',
      );
    final String output = '${webDir.path}/sqlite_opfs_worker.js';
    stdout.writeln('Compiling the OPFS worker to $output');
    final ProcessResult result = await Process.run(
      Platform.resolvedExecutable,
      <String>[
        'compile',
        'js',
        '-O2',
        '--packages=${packageConfig.path}',
        '-o',
        output,
        entry.path,
      ],
    );
    if (result.exitCode != 0) {
      stderr
        ..write(result.stdout)
        ..write(result.stderr)
        ..writeln('Could not compile the OPFS worker.');
      exitCode = 1;
      return;
    }
    // Only the compiler needs it.
    final File deps = File('$output.deps');
    if (deps.existsSync()) {
      deps.deleteSync();
    }
  }

  final File wasm = File('${webDir.path}/sqlite3.wasm');
  stdout.writeln();
  if (sqlite3Version == null) {
    stdout.writeln(
      'Could not tell which sqlite3 version your app resolves. Put the '
      'sqlite3.wasm of that version (an asset of the release '
      '"sqlite3-<version>" of https://github.com/simolus3/sqlite3.dart/releases) '
      'at ${wasm.path}.',
    );
    return;
  }
  final String url =
      'https://github.com/simolus3/sqlite3.dart/releases/download/'
      'sqlite3-$sqlite3Version/sqlite3.wasm';
  stdout
    ..writeln('Your app resolves sqlite3 $sqlite3Version. The page loads the')
    ..writeln('sqlite3.wasm of exactly that version; download it once with')
    ..writeln()
    ..writeln('  curl -fL -o ${wasm.path} \\')
    ..writeln('    $url')
    ..writeln()
    ..writeln('and compare its sha256 with the one the release page shows.')
    ..writeln('Do it again when the sqlite3 version in pubspec.lock changes.');
  if (wasm.existsSync()) {
    stdout.writeln(
      '(${wasm.path} exists; this tool cannot tell which version it is.)',
    );
  }
}

/// [relative] in the current directory or the closest parent that has it.
File? _findUp(String relative) {
  Directory dir = Directory.current.absolute;
  while (true) {
    final File file = File('${dir.path}/$relative');
    if (file.existsSync()) {
      return file;
    }
    final Directory parent = dir.parent;
    if (parent.path == dir.path) {
      return null;
    }
    dir = parent;
  }
}

/// The resolved version of `sqlite3`: from the pubspec.lock next to the
/// package config (a workspace has one at its root), else from the folder
/// name of a hosted package in the package config.
String? _sqlite3Version(File packageConfig) {
  final File lock = File('${packageConfig.parent.parent.path}/pubspec.lock');
  if (lock.existsSync()) {
    final RegExpMatch? match = RegExp(
      r'^  sqlite3:\n(?:    .*\n)*?    version: "([^"]+)"',
      multiLine: true,
    ).firstMatch(lock.readAsStringSync());
    if (match != null) {
      return match.group(1);
    }
  }
  try {
    final Object? json = jsonDecode(packageConfig.readAsStringSync());
    final List<Object?> packages =
        (json! as Map<String, Object?>)['packages']! as List<Object?>;
    for (final Object? package in packages) {
      final Map<String, Object?> entry = package! as Map<String, Object?>;
      if (entry['name'] == 'sqlite3') {
        final RegExpMatch? match = RegExp(
          r'sqlite3-(\d[^/]*)/?$',
        ).firstMatch(entry['rootUri']! as String);
        return match?.group(1);
      }
    }
  } on Object {
    // Not readable: the caller says so.
  }
  return null;
}
