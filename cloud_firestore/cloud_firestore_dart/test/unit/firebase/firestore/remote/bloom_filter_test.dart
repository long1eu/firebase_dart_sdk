import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:cloud_firestore_dart/src/firebase/firestore/remote/bloom_filter.dart';
import 'package:test/test.dart';

const String goldenDocumentPrefix =
    'projects/project-1/databases/database-1/documents/coll/doc';
const String goldenTestLocation = 'test/res/bloom_filter_golden_test_data/';

Uint8List bytes(List<int> values) => Uint8List.fromList(values);

Matcher createExceptionWith(List<String> parts) {
  return isA<BloomFilterCreateException>().having(
      (BloomFilterCreateException e) => e.message.toLowerCase(),
      'message',
      allOf(parts.map((String p) => contains(p.toLowerCase())).toList()));
}

Map<String, dynamic> readJsonFile(String fileName) {
  return jsonDecode(File('$goldenTestLocation$fileName').readAsStringSync())
      as Map<String, dynamic>;
}

/// Golden tests are generated by the backend by inserting n document paths
/// into a bloom filter. The document path is [goldenDocumentPrefix] followed by
/// the number, e.g. `.../coll/doc12`. The result file holds the membership of
/// documents 0 to 2n: the first n must be members, the others are not members
/// apart from some false positives.
void runGoldenTest(String testFile) {
  final String resultFile =
      testFile.replaceFirst('bloom_filter_proto', 'membership_test_result');
  expect(resultFile, isNot(testFile));

  final Map<String, dynamic> testJson = readJsonFile(testFile);
  final Map<String, dynamic> resultJson = readJsonFile(resultFile);

  final Map<String, dynamic> bits = testJson['bits'];
  final String bitmap = bits['bitmap'];
  final int padding = bits['padding'];
  final int hashCount = testJson['hashCount'];
  final BloomFilter bloomFilter =
      BloomFilter.create(base64.decode(bitmap), padding, hashCount);

  final String membershipTestResults = resultJson['membershipTestResults'];
  for (int i = 0; i < membershipTestResults.length; i++) {
    final bool expectedResult = membershipTestResults[i] == '1';
    final bool mightContainResult =
        bloomFilter.mightContain('$goldenDocumentPrefix$i');
    expect(mightContainResult, expectedResult,
        reason: 'For document $goldenDocumentPrefix$i mightContain() returned '
            '$mightContainResult, but expected $expectedResult');
  }
}

void main() {
  test('instantiateEmptyBloomFilter', () {
    expect(BloomFilter(Uint8List(0), 0, 0).bitCount, 0);
  });

  test('instantiateNonEmptyBloomFilter', () {
    expect(BloomFilter(bytes(<int>[1]), 0, 1).bitCount, 8);
    expect(BloomFilter(bytes(<int>[1]), 7, 1).bitCount, 1);
  });

  test('constructorShouldThrowOnInvalidArguments', () {
    expect(() => BloomFilter(Uint8List(0), 1, 0), throwsArgumentError);
    expect(() => BloomFilter(bytes(<int>[1]), 1, 0), throwsArgumentError);
    expect(() => BloomFilter(bytes(<int>[1]), 8, 1), throwsArgumentError);
  });

  test('createShouldCreateAnEmptyBloomFilter', () {
    expect(BloomFilter.create(Uint8List(0), 0, 0).bitCount, 0);
  });

  test('createShouldCreateNonEmptyBloomFilter', () {
    expect(BloomFilter.create(bytes(<int>[1]), 0, 1).bitCount, 8);
    expect(BloomFilter.create(bytes(<int>[1]), 7, 1).bitCount, 1);
  });

  test('createShouldThrowOnEmptyBloomFilterWithNonZeroPadding', () {
    expect(
        () => BloomFilter.create(Uint8List(0), 1, 0),
        throwsA(createExceptionWith(
            <String>['padding of 0', 'bitmap length is 0', 'got 1'])));
  });

  test('createShouldThrowOnNonEmptyBloomFilterWithZeroHashCount', () {
    expect(() => BloomFilter.create(bytes(<int>[1]), 1, 0),
        throwsA(createExceptionWith(<String>['hash count: 0'])));
  });

  test('createShouldThrowOnNegativePadding', () {
    expect(() => BloomFilter.create(Uint8List(0), -1, 0),
        throwsA(createExceptionWith(<String>['padding: -1'])));
    expect(() => BloomFilter.create(bytes(<int>[1]), -1, 1),
        throwsA(createExceptionWith(<String>['padding: -1'])));
  });

  test('createShouldThrowOnNegativeHashCount', () {
    expect(() => BloomFilter.create(Uint8List(0), 0, -1),
        throwsA(createExceptionWith(<String>['hash count: -1'])));
    expect(() => BloomFilter.create(bytes(<int>[1]), 1, -1),
        throwsA(createExceptionWith(<String>['hash count: -1'])));
  });

  test('createShouldThrowIfPaddingIsTooLarge', () {
    expect(() => BloomFilter.create(bytes(<int>[1]), 8, 1),
        throwsA(createExceptionWith(<String>['padding: 8'])));
  });

  test('mightContainCanProcessNonStandardCharacters', () {
    // A non-empty BloomFilter object with 1 insertion : "ÀÒ∑"
    final BloomFilter bloomFilter = BloomFilter(bytes(<int>[237, 5]), 5, 8);
    expect(bloomFilter.mightContain('ÀÒ∑'), isTrue);
    expect(bloomFilter.mightContain('Ò∑À'), isFalse);
  });

  test('mightContainOnEmptyBloomFilterShouldReturnFalse', () {
    final BloomFilter bloomFilter = BloomFilter(Uint8List(0), 0, 0);
    expect(bloomFilter.mightContain(''), isFalse);
    expect(bloomFilter.mightContain('a'), isFalse);
  });

  test('mightContainWithEmptyStringMightReturnFalsePositiveResult', () {
    expect(BloomFilter(bytes(<int>[1]), 1, 1).mightContain(''), isFalse);
    expect(BloomFilter(bytes(<int>[255]), 0, 16).mightContain(''), isTrue);
  });

  test('toStringOnEmptyBitmap', () {
    final String result = BloomFilter(Uint8List(0), 0, 0).toString();
    expect(result, startsWith('BloomFilter{'));
    expect(result, endsWith('}'));
    expect(result, contains('hashCount=0'));
    expect(result, contains('size=0'));
    expect(result, contains('bitmap=""'));
  });

  test('toStringOnNonEmptyBitmap', () {
    final String result =
        BloomFilter(bytes(<int>[0x01, 0xAE, 0xFF]), 3, 7).toString();
    expect(result, startsWith('BloomFilter{'));
    expect(result, endsWith('}'));
    expect(result, contains('hashCount=7'));
    expect(result, contains('size=21'));
    expect(result, contains('bitmap="Aa7/"'));
  });

  for (final int documents in <int>[1, 500, 5000, 50000]) {
    for (final String rate in <String>['1', '01', '0001']) {
      test('goldenTest_${documents}Document_${rate}FalsePositiveRate', () {
        runGoldenTest(
            'Validation_BloomFilterTest_MD5_${documents}_${rate}_bloom_filter_proto.json');
      });
    }
  }
}
